package node

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"runtime"
	"strings"

	"github.com/mahantsunandan/locnet/internal/netmap"
)

// The managed block is delimited so that everything outside it is left exactly
// as the operator wrote it. Rewriting a whole hosts file would be a good way
// to break a machine that depends on an entry we did not put there.
const (
	hostsBegin = "# BEGIN LocNet — managed block, do not edit by hand"
	hostsEnd   = "# END LocNet"
)

// HostsPath is the system hosts file for this platform.
func HostsPath() string {
	if p := os.Getenv("LOCNET_HOSTS_FILE"); p != "" {
		return p
	}
	if runtime.GOOS == "windows" {
		root := os.Getenv("SystemRoot")
		if root == "" {
			root = `C:\Windows`
		}
		return root + `\System32\drivers\etc\hosts`
	}
	return "/etc/hosts"
}

// writeHosts replaces the managed block with one line per peer.
//
// This is opt-in, and it is the closest thing LocNet has to MagicDNS: after it
// runs, `ssh luke` reaches the node named luke without anyone editing a config
// file. It is a deliberate simplification — a real resolver would handle
// search domains and negative caching — but it costs nothing and it is what
// makes the network feel like a network rather than a list of addresses.
func writeHosts(nm *netmap.NetMap) error {
	var block bytes.Buffer
	block.WriteString(hostsBegin + "\n")
	fmt.Fprintf(&block, "# network: %s   generated by locnetd\n", nm.Network.Name)

	entries := append([]netmap.Node{nm.Self}, nm.Peers...)
	for _, n := range entries {
		if !n.IP.IsValid() || n.Name == "" {
			continue
		}
		if nm.Network.Domain != "" {
			fmt.Fprintf(&block, "%s\t%s %s.%s\n", n.IP, n.Name, n.Name, nm.Network.Domain)
		} else {
			fmt.Fprintf(&block, "%s\t%s\n", n.IP, n.Name)
		}
	}
	block.WriteString(hostsEnd + "\n")
	return replaceBlock(block.String())
}

// clearHosts removes the managed block.
func clearHosts() error { return replaceBlock("") }

func replaceBlock(block string) error {
	path := HostsPath()
	existing, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) && block == "" {
			return nil
		}
		return fmt.Errorf("read %s: %w", path, err)
	}

	var out bytes.Buffer
	inBlock := false
	sc := bufio.NewScanner(bytes.NewReader(existing))
	sc.Buffer(make([]byte, 0, 64*1024), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		switch {
		case strings.HasPrefix(line, hostsBegin):
			inBlock = true
		case inBlock && strings.HasPrefix(line, hostsEnd):
			inBlock = false
		case !inBlock:
			out.WriteString(line)
			out.WriteByte('\n')
		}
	}
	if err := sc.Err(); err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}
	if inBlock {
		// The end marker was missing, so everything after the begin marker
		// was swallowed. Refuse rather than truncate someone's hosts file.
		return fmt.Errorf("%s has a LocNet block with no %q line; fix it by hand and try again", path, hostsEnd)
	}

	trimmed := bytes.TrimRight(out.Bytes(), "\n")
	final := append(trimmed, '\n')
	if block != "" {
		final = append(final, '\n')
		final = append(final, block...)
	}

	// A new network map arrives every time any machine's load moves, and
	// almost none of them change a name or an address. Rewriting an
	// unchanged system file on each one is wear for nothing, and it wakes
	// every program that watches /etc/hosts.
	if bytes.Equal(final, existing) {
		return nil
	}

	// Written in place rather than via a temp file and rename: on Windows
	// the hosts file is frequently held open by security software, and a
	// rename onto it fails where a write succeeds.
	return os.WriteFile(path, final, 0o644)
}
